// Package rbac 角色能力矩阵机制：角色→能力集查表（Can）、只读档由矩阵推导、
// 授权面指纹（Snapshot）、「矩阵不得装饰化」的 lint 骨架。
//
// # 只收机制，词表是宿主数据
//
// 本包**不预设任何具体角色名或能力词**——"admin"、"platform.read"、
// "session.write" 这些是宿主领域词汇，经 Matrix 与 writeFace 词表注入。
// 这条边界是下沉提案 #175 (e) 的核心风险对面：词表一旦长进机制里，包就
// 落成某一个宿主的专用件。本包的类型与方法对任何词表形状同等工作。
//
// # 与 permgate 的分工边界（角色面 vs 调用面）
//
// 同仓的 permgate 与本包是**权限判定的两半**，不可互相替代：
//
//   - permgate 裁「**这次调用**要不要人确认」——调用面。输入是一次具体的
//     工具调用（工具名 + 输入内容 + 会话模式 + 规则链），输出 allow/ask/deny，
//     关心的是交互（弹窗/会话钥匙/白名单 break-glass）。
//   - rbac 裁「**这个角色**有没有这个能力」——角色面。输入是身份（角色）
//     与能力词，输出是静态布尔，关心的是授权真相的单源（矩阵）。
//
// 典型组合：handler 侧 requirePerm 用 rbac.Can 做能力预判（角色没这个能力
// 连工具都不该调到）；permgate 管调到了之后的确认链（这次调用要不要人）。
// 角色面通过的调用仍可能被调用面拦下（permgate 的 ask/deny）；反过来，
// permgate 放行不构成角色授权——两套判定各管各的真相。
//
// # fail-closed 缺省
//
//   - Can：未声明角色/能力词 → false（矩阵外没有能力）。
//   - ReadOnly：写面词表 nil/空 → 无法证明任何能力是读面 → 一律推导为
//     只读（写面全禁）——漏声明得到的是「全禁」，不是「全放」。不在矩阵
//     里的角色同理（能力集为空 = 无写面 = 只读档）。
//
// # 踩坑纪律（#175 (d)：随机制一起下沉的两条）
//
//   - **只读档由矩阵推导，不硬编码角色名**：`role == "viewer"` 式硬编码在
//     矩阵演进（新增只读角色、调整能力词）时静默失真——声明面改了、执行面
//     没跟上，授权真相从此分叉。判据恒为「能力集不含写面能力」。
//   - **矩阵不得装饰化**：矩阵里每条能力词必须有执行面消费点（requirePerm /
//     Can 调用点），否则矩阵退化成「看起来有授权体系」的装饰品——多写的
//     能力词没人拦、删掉的能力词没人发现。lint 骨架（Matrix.Lint）落实
//     三条判据：每条能力词有消费点、角色词表闭合、矩阵单调（高层 ⊇ 低层）；
//     消费点回调与角色词表由宿主注入。
//
// # 并发契约
//
// Matrix 是宿主持有的声明面数据：本包所有方法只读入参、无共享可变状态，
// 并发安全。矩阵变更属装配期动作——运行期热更请整体替换 Matrix 值（与
// permgate.Service.Update 的换值纪律同款），不得原地改切片元素。
//
// 零第三方依赖（纯 stdlib + slices）。
