// Package sandbox 执行沙箱的**档位语义**与**后端协议**。
//
// # 这个包解决什么
//
// 「模型写的程序在哪跑、跑起来能触达什么」这件事若只有一个写死的答案（进程内
// 解释器），那么「它跑在够强的隔离里吗」就无处声明——只能靠人记得别挑错后端。
//
// 本包把它变成可声明、可判定的机制：
//
//   - Level：隔离档位（进程内解释器 → 内核级 → 硬件虚拟化），单调可比；
//   - Provider：后端协议（自报提供哪一档，并执行程序）；
//   - Registry：登记簿，按「要求档位」选后端。
//
// # 为什么「选不到就拒绝」是本包的核心语义
//
// 隔离要求若在「没有满足档位的后端」时被**降级**（拿弱后端跑），那么档位这套
// 机制就是装饰：宿主写下的「本次要内核级」与实际发生的「进程内跑」之间没有任何
// 信号，差的那个量级就是全量暴露。
//
// 故 Resolve 在无满足者时返回错误，**不静默降级**。宿主于是必须显式面对
// 「这个环境没有我需要的隔离档位」——要么补后端，要么把要求降到自己承担得起的
// 档位。两个都是有意识的动作；降级不是。
//
// # 与本仓 invoke 包的关系
//
// invoke 管的是「一次工具调用要不要放行」（判定环），本包管的是「一段被执行的
// 程序跑在什么隔离档位上」（执行环境）。两者是**不同的执行点**，不要混成一条链：
// 把本包做成 invoke 的一环，需要去猜「哪个参数字段是程序体」，那是宿主知识，
// 不该进原语层。
//
// 反过来，本包要接进 invoke 的判定环时，是**宿主**在装配期把两者接起来
// （把「本次执行的档位要求」变成一个 Stage），本包只认协议，不认装配。
//
// # 为什么档位归安全层（tier 0）而不是工具治理层
//
// 「信任边界移动了，沙箱没跟着移动」是本仓 invoke 包的立论之一——而它指出的正是
// 缺少一个**可声明的档位概念**：此前只有「有没有沙箱」的二元说法，没有「够不够强」
// 的说法，于是「隔离降级了」这类事故无法在装配期被发现，只能靠事后审计。
//
// 档位语义与判定语义同族（都是「要求 vs 实际」的对照），故与 invoke / permgate
// 同处安全层。
//
// # 边界：档位语义归本包，「哪些执行要哪一档」归宿主
//
// 本包不认识任何领域概念，也不替宿主决定档位要求——要求是宿主按自己的风险面
// 声明的（那是判断，不是机制）。本包只保证一件事：**声明的档位与实际执行的后端
// 之间没有静默落差**。
//
// # 已知局限：档位是后端自报的，本包不校验其真实性
//
// Provider.Level() 是后端自己写的常量，本包无法机械判定「这个后端真的提供了
// 这么强的隔离」。因此：宿主若不信任某个后端，唯一的办法是**不登记它**。
// 本包不假装自己能验证隔离强度——那需要审后端实现，不是判据能做的事。
package sandbox
