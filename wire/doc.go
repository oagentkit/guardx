// Package wire 执行沙箱的**跨进程调用协议**。
//
// # 它解决什么
//
// 沙箱档位（Level）答的是「能力面多强」，预算支持面（Capable）答的是「资源兜底
// 兑现哪几项」。但这两者都还缺一块：**程序一旦出宿主进程，工具回调就够不着了**。
//
// 进程内执行（goja VM 跑在宿主进程里）时，程序里的 `host.<tool>()` 是一次普通
// Go 函数调用；程序出宿主进程后，它变成一次**跨进程 IPC**。这段 IPC 若由每个
// 后端各写一遍，就会有一堆互不兼容的私有协议——而协议恰恰是最不该私有的东西
// （它决定了「子进程里的程序怎么跟父侧说话」，换个后端就得换一套）。
//
// 故本包把协议**收成一份**：帧格式、请求/响应语义、父侧服务端循环、子侧客户端。
// 后端只实现「怎么起这个进程」与「怎么执行这个程序」。
//
// # 帧格式
//
// 长度前缀 + JSON：
//
//	┌───────────────┬──────────────────────────────┐
//	│ 4B 大端长度 N  │ N 字节 JSON 负载             │
//	└───────────────┴──────────────────────────────┘
//
// **不用行分隔**——工具输出可能含换行，行分隔会被内容切断（一条多行的日志就能
// 把后面的帧全毁掉）。长度前缀对负载内容零假设。
//
// # 六条不变量
//
//  1. **版本响亮失败**：`v` 不匹配即拒，不静默错配。错配的症状是「字段读成了
//     另一个意思」——那是最难查的一类，故不静默。
//  2. **失败分类跨进程同源**：`kind` 取 `guardx/toolfail` 的分类，**不是**自由
//     字符串。分类一旦退化成字符串，父侧就分不清「可重试」与「永久拒绝」，
//     重试策略随之瞎掉。`toolfail` 与 `sandbox` 同在 guardx——**同层引用，
//     无跨仓依赖**。
//  3. **预算的权威在父侧**：调用数与输出字节数由**父侧**记账。子进程只是执行者
//     ——若子进程自己记账，它可以谎报自己没超预算。
//  4. **在途调用有硬上限**：总量预算（MaxCalls）拦不住「瞬间发起十万次并发
//     调用」——那时它们都还没返回，父侧已被 goroutine 淹没。故父侧另设**在途
//     并发上限**，超出即回「超限」。这是**可用性**约束，与 MaxCalls 的**配额**
//     约束是两件事。
//  5. **取消传播**：父侧 ctx 取消 → 取消在途调用 + 通知子进程终止（否则子进程
//     继续跑，父侧却已经返回了）。
//  6. **响应按 `id` 关联，不按到达顺序**：程序里多个 await 是并发的，返回顺序与
//     请求顺序无关。
//
// # 谁该用它
//
// 后端实现方（如 agent-harness 的 ptc 子进程后端）：起进程、连管道、跑程序；
// **协议本身用本包的 Transport / Server / Client**。
//
// 宿主：只声明「这次执行要哪一档 + 哪些预算项」，不碰协议。
package wire
