// Package invoke 提供不可绕过的工具调用链：门禁链由构造保证，而不是由调用点的自觉保证。
//
// # 为什么要有这个包
//
// 本仓既有的三包都只能**加**约束，没有一个能**强制**约束：
//
//   - policy.AuditGate 是装饰器——宿主忘了包一层，这次调用就没有审计门；
//   - toolsched 做的是调度与去重，不参与判定；
//   - toolprior 是优先级表，同样是数据不是闸。
//
// 「宿主忘了包」是个非常现实的失效形态：它不报错、不告警，工具照常执行，
// 事后从日志里也看不出这次调用没走审计门。OpenCode 2.0 上线一周内爆出的三个
// 安全回归（配置热重载窗口绕过 provider deny、系统级配置目录被静默丢弃、
// TUI 层 sandbox 在工具执行搬进后台服务后静默失效）全部属于同一形态：
// **信任边界移动了，沙箱没跟着移动**，而且静默。
//
// 所以本包的立论是：把门禁从「装饰」改成「结构」。
//
// # 结构在哪
//
// NewChain 把 Handler **按值收进私有字段**，此后不再对外暴露。于是：
//
//   - 想执行一次调用，唯一的办法就是 chain.Do，它必然过完整条链；
//   - 宿主无法拿到裸 Handler 再绕过链去调——那个函数值已经被链吞掉了；
//   - 链不可变（构造后 stages 只读），并发下多个调用共享同一条链没有竞态。
//
// 这条不变量是**类型层面**的，不是约定层面的：绕过代码写不出来。
//
// # 环语义只有一份
//
// Chain.Do 之外还有一类调用方：执行体不归自己管，链用不上。典型形态是程序化编排——
// 模型写的一段代码在沙箱里跑，代码里的 host.<tool>() 调宿主工具，那种执行体必须
// 跑在沙箱绑定闭包里（写回预算记账、追加调用账目、打断 VM），压根没法交给 Chain.Do。
//
// 这类调用方最容易长出一份「自己排的环」。而复制一份环的代价不是代码重复，是**漂移**：
// 环 panic 与环报错的归口环节名（stageInternal）与 Cause 都是包内未导出常量，
// 下游既不能引用也不能可靠复制（硬编码字符串等于与实现耦合）。漏掉的直接后果是——
// 经那条路径触发的守卫 panic，被谎报成「守卫正常拒绝了」：调用方拿着错误去修策略，
// 而真正该修的是守卫代码。
//
// 因此求值环只有一个导出入口 EvaluateStages，Chain.Do 自己也调它：一份语义，两处受益，
// panic 归口只存在于本包一处。它不持有执行体（返回类型只有 error），所以不构成
// 绕过链的出口——绕过需要 Handler，而 Handler 只有 NewChain 内部拿得到。
//
// # 与审计面的一致性
//
// 一次调用无论结局是放行、拒绝、阶段报错还是 panic，Do 都**恰好**产出一条 Record。
// 这条同样重要：本仓此前存在审计面不对称——经 Code Mode 的调用有完整调用账目，
// 普通调用没有对等物。能力更强的路径审计更好，会让人在评审时高估整体覆盖。
//
// # 两层结论：门禁层与动作层
//
// 一次调用有**两个**结论，分属两层事实：
//
//   - **门禁层**（Record.Allowed / Record.Err）：门禁判了什么。
//   - **动作层**（Record.Outcome）：事情做没做。
//
// 链只保证**门禁层**恰好一条 Record——那是链能看见的东西：capability、
// confirm 标志、每一环的判定。「命令是什么」只有工具知道，于是「工具自己在
// 执行体里拒了这次动作」或「这次只是演练」只能由执行体给出结论。
//
// 只留门禁层会漏掉一整类结局：工具自拒（缺 confirm）或演练（什么都没跑，
// 但这是调用方要的）都以**一次成功返回**结束 ⇒ 门禁层长成 Allowed=true、Err=nil，
// 而 Allowed 读起来是「执行了」。于是链只保证门禁层恰好一条 Record；
// **动作层结论由执行体在 Result.Outcome 里显式给出，链原样抄进 Record.Outcome**，
// 未声明时按「执行了」处理，保持既有调用方行为不变。
//
// 「拒绝」与「演练」在 Outcome 里是两个独立字段，不是同一个 bool 的两种取值：
// 合成之后下游一定会把演练记成拒绝——那是在审计唯一要回答的问题上造假警报。
//
// # fail-closed
//
// 构造期与执行期都偏向拒绝：
//
//   - NewChain(nil handler) 直接构造失败，不返回一个「空转」的链；
//   - 空工具名按拒绝处理（门禁不该对空名乐观放行）；
//   - Stage 返回 error 时按拒绝处理，不是按「跳过该环」处理；
//   - Stage 或 Handler panic 时被 recover 并转成错误，不杀编排进程。
